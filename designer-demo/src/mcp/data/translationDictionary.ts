/**
 * 从词典获取翻译，如果没有则返回空数组
 */
export function translate(word: string): string[] {
  const lowerWord = word.toLowerCase();
  return TRANSLATION_DICT[lowerWord] || [];
}

/**
 * 批量翻译多个单词
 */
export function translateWords(words: string[]): string[] {
  return words.flatMap(word => translate(word));
}
